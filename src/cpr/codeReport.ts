/**
 * Plain-text CPR record built from the code clock's event log.
 *
 * Layout: a patient header, a summary line (duration · cycles · outcome), one
 * line per logged event ("mm:ss  what happened"), and a closing line that
 * credits the guideline the timings were cited from and states that the record
 * is a timekeeping aid — not a medical record. Hebrew and English are
 * authored; every other UI language falls back to English.
 */
import { L, tr, type LocalizedText } from '../types/toxins';
import type { Lang } from '../i18n/languages';
import type { Species } from '../types';
import { formatClock, readClock, type CodeClockState, type CodeEvent, type CodeEventKind } from './codeClock';
import { RECOVER_2024 } from './recoverGuideline';

export interface ReportPatient {
  name?: string;
  species: Species;
  weightKg: number;
}

export const CODE_EVENT_LABEL: Record<CodeEventKind, LocalizedText> = {
  'code-started': L('החייאה החלה', 'CPR started'),
  'pause-check': L('עצירה ובדיקה', 'Pause & check'),
  'compressions-resumed': L('עיסויים חודשו', 'Compressions resumed'),
  epinephrine: L('אפינפרין', 'Epinephrine'),
  vasopressin: L('וזופרסין', 'Vasopressin'),
  atropine: L('אטרופין', 'Atropine'),
  lidocaine: L('לידוקאין', 'Lidocaine'),
  amiodarone: L('אמיודרון', 'Amiodarone'),
  esmolol: L('אסמולול', 'Esmolol'),
  reversal: L('תרופת היפוך', 'Reversal agent'),
  shock: L('הלם חשמלי', 'Shock'),
  intubated: L('אינטובציה', 'Intubated'),
  'iv-access': L('גישה ורידית', 'IV access'),
  'io-access': L('גישה תוך-גרמית', 'IO access'),
  note: L('הערה', 'Note'),
  rosc: L('חזרת מחזור דם (ROSC)', 'ROSC'),
  stopped: L('ההחייאה הופסקה', 'CPR stopped'),
};

const SPECIES_LABEL: Record<Species, LocalizedText> = {
  dog: L('כלב', 'Dog'),
  cat: L('חתול', 'Cat'),
};

const TEXT = {
  title: L('רישום החייאה', 'CPR record'),
  kg: L('ק"ג', 'kg'),
  duration: L('משך', 'Duration'),
  cycle: L('מחזור', 'cycle'),
  cycles: L('מחזורים', 'cycles'),
  outcome: L('תוצאה', 'Outcome'),
  inProgress: L('בתהליך', 'in progress'),
  endOfCycle: L('סוף מחזור', 'end of cycle'),
  pause: L('עצירה', 'pause'),
  secondsShort: L('שנ׳', 's'),
  footer: L(
    `זמנים ומינונים מצוטטים מהנחיות RECOVER 2024 (${RECOVER_2024.organisation}, ${RECOVER_2024.organisationUrl}). הרישום הופק ב-Vet-Holim — עזר לתזמון בלבד, אינו רשומה רפואית; יש לאמת מול הרישום הקליני.`,
    `Timings and doses cited from the 2024 RECOVER Guidelines (${RECOVER_2024.organisation}, ${RECOVER_2024.organisationUrl}). Record generated by Vet-Holim — a timekeeping aid, not a medical record; verify against the clinical notes.`,
  ),
};

function headerLine(patient: ReportPatient, lang: Lang): string {
  const parts = [tr(SPECIES_LABEL[patient.species], lang), `${patient.weightKg} ${tr(TEXT.kg, lang)}`];
  if (patient.name?.trim()) parts.unshift(patient.name.trim());
  return `${tr(TEXT.title, lang)} — ${parts.join(' | ')}`;
}

function outcomeText(state: CodeClockState, lang: Lang): string {
  const last = state.events.at(-1);
  const ended = last && (last.kind === 'rosc' || last.kind === 'stopped');
  return ended ? tr(CODE_EVENT_LABEL[last.kind], lang) : tr(TEXT.inProgress, lang);
}

function summaryLine(state: CodeClockState, lang: Lang): string {
  const reading = readClock(state, state.endedAtMs ?? Date.now());
  const cycleWord = tr(reading.cycleNumber === 1 ? TEXT.cycle : TEXT.cycles, lang);
  return [
    `${tr(TEXT.duration, lang)} ${formatClock(reading.elapsedMs)}`,
    `${reading.cycleNumber} ${cycleWord}`,
    `${tr(TEXT.outcome, lang)}: ${outcomeText(state, lang)}`,
  ].join(' | ');
}

function eventSuffix(event: CodeEvent, lang: Lang): string {
  if (event.kind === 'pause-check') return ` (${tr(TEXT.endOfCycle, lang)} ${event.cycle})`;
  if (event.pauseMs !== undefined) {
    return ` — ${tr(TEXT.pause, lang)} ${Math.round(event.pauseMs / 1000)} ${tr(TEXT.secondsShort, lang)}`;
  }
  return event.detail ? ` — ${event.detail}` : '';
}

function eventLine(event: CodeEvent, lang: Lang): string {
  return `${formatClock(event.atMs)}  ${tr(CODE_EVENT_LABEL[event.kind], lang)}${eventSuffix(event, lang)}`;
}

export function buildCodeReport(input: {
  state: CodeClockState;
  patient: ReportPatient;
  lang: Lang;
}): string {
  const { state, patient, lang } = input;
  return [
    headerLine(patient, lang),
    summaryLine(state, lang),
    '',
    ...state.events.map((event) => eventLine(event, lang)),
    '',
    tr(TEXT.footer, lang),
  ].join('\n');
}
